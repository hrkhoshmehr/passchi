// قیمت‌ها از هزینهٔ واقعی درمی‌آیند، نه از حدس. سه عدد زیر تنها فرض‌های این
// محاسبه‌اند و هرکدام جداگانه قابل به‌روزرسانی است. `scripts/pricing.mjs`
