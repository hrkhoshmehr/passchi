/**
 * تعداد نفراتی که وقتی مالک تعدادی نمی‌گوید، پیش‌فرض گرفته می‌شود.
 *
 * ده نفر، چون در یک گروه کلاسی واقعی به‌راحتی جمع می‌شود.
 */
export const SHARE_TARGET = 10;

/**
 * سقف بازگشت به فرستنده — و چرا صد درصد نیست.
 *
 * بازپرداخت، سکه‌های خریداری‌شده را به فرستنده برمی‌گرداند و او دوباره
 * خرجشان می‌کند. با نرخ بازگشت r، هر خرید در نهایت **۱/(۱−r)** برابر خودش
 * پردازش می‌خرد. با r=۰٫۹ یعنی ده برابر، در حالی که حاشیهٔ ما بین ۲٫۴ تا ۳
 * برابر است — پس نرخ سربه‌سر حوالی ۶۰٪ می‌افتد.
 *
 * بدتر اینکه بازپرداخت از جیب کسانی می‌آید که می‌پیوندند، و اگر حساب تازه
 * باشند سهمشان را با سکهٔ *هدیه* می‌دهند: پولی وارد نشده ولی سکهٔ واقعیِ
 * فرستنده برگشته است. با ۹۰٪ بازگشت، یک خریدِ ۴۴۹ هزار تومانی در شبیه‌سازی
 * ۱٫۶ میلیون تومان هزینه روی دست ما می‌گذاشت.
 *
 * پنجاه درصد فاصلهٔ امنی تا نرخ سربه‌سر دارد و هنوز پیشنهاد قابل‌گفتنی است:
 * «نصف سکه‌هات برمی‌گرده». `scripts/economics.mjs` این را می‌سنجد.
 */
export const REFUND_CAP_PCT = 0.5;

/**
 * کمترین تعدادی که مالک می‌تواند بگوید — و چرا کف دارد.
 *
 * `seat = ceil(cap/n)` است، پس هرچه `n` کوچک‌تر، سهمِ هر نفر بزرگ‌تر. با
 * «۱ نفر» سهم می‌شد **نصفِ کلِ جلسه**: روی یک کلاس ۹۰ سکه‌ای یعنی ۴۵ سکه،
 * بیشتر از ۲۰ سکهٔ هدیه‌ای که تازه‌وارد دارد. یعنی اولین هم‌کلاسی که روی
 * لینک می‌زد به دیوار می‌خورد — و مالک هیچ‌وقت نمی‌فهمید چرا کسی برنداشت.
 *
 * دلیل دوم اقتصادی است: هرچه `n` کوچک‌تر، یک حسابِ ساختگی بیشترِ سقف را در
 * یک برداشت به مالک برمی‌گرداند. با «۱ نفر» یک حسابِ جعلی کلِ نصفِ هزینه را
 * پس می‌داد؛ با کفِ پنج، همان کار پنج حساب و پنج برابر سکهٔ واقعی می‌خواهد.
 *
 * پنج، چون روی کلاس ۹۰ سکه‌ای سهم را ۹ سکه می‌کند — راحت داخل هدیهٔ ۲۰
 * سکه‌ای — و هنوز کوچک‌ترین «گروه درسِ» باورپذیر است.
 */
export const SHARE_TARGET_MIN = 5;

/**
 * سهمِ ثابتِ هر نفر و سقفِ بازگشتِ مالک، وقتی جلسه با `people` هم‌کلاسی
 * تقسیم شود.
 *
 * مالک تعداد را می‌گوید و از همان‌جا `seat` درمی‌آید: هزینه‌ای که هر
 * هم‌کلاسی هنگام برداشتن می‌دهد، ثابت و از پیش معلوم. همان مبلغ به حساب
 * مالک برمی‌گردد تا جمعِ بازگشت به `cap` (نصفِ هزینه) برسد؛ از آن به بعد
 * برداشتن رایگان است.
 *
 * `seat` را طوری می‌گیریم که `people` نفر تقریباً سقف را پر کنند، پس با
 * «۵ نفر» هرکدام یک‌پنجمِ سقف را می‌دهند. `fills` می‌گوید تقریباً چند نفر
 * لازم است تا سقف پر شود.
 *
 * کفِ `SHARE_TARGET_MIN` **اینجا هم** اعمال می‌شود، نه فقط موقع ذخیره‌کردن:
 * جلسه‌هایی که پیش از این قاعده با `share_target = 1` در پایگاه‌داده نشسته‌اند
 * وگرنه تا ابد سهمِ نصفِ‌کلاس می‌گرفتند و لینکشان برای تازه‌وارد بن‌بست
 * می‌ماند. با کف‌گذاشتن اینجا، همان ردیف‌های قدیمی هم بی‌مهاجرت درمان می‌شوند.
 */
export function shareBack(
  costSec: number,
  people = SHARE_TARGET,
): { seat: number; cap: number; fills: number } {
  const total = costCoins(costSec);
  const cap = Math.floor(total * REFUND_CAP_PCT);
  const n = Math.max(SHARE_TARGET_MIN, Math.round(people));
  const seat = Math.max(1, Math.ceil(cap / n));
  return { seat, cap, fills: Math.ceil(cap / seat) };
}

export function findPackage(id: string): CoinPackage | null {
  return PACKAGES.find((p) => p.id === id) ?? null;
}

/**
 * تقریبِ تومانیِ یک مقدار سکه — برای لحظهٔ تصمیم خرید.
 *
 * «۶۳۰ سکه» به کسی که تازه آمده هیچ نمی‌گوید، و برای فهمیدنش باید یک کلیک
 * دیگر تا صفحهٔ شارژ برود. آن کلیک جایی است که آدم‌ها می‌روند — نه چون قیمت
 * زیاد است، چون نامعلوم است و نامعلوم همیشه بدتر از واقعیت تخمین زده می‌شود.
 *
 * نرخِ **ارزان‌ترین** پکیج ملاک است تا عددی که نشان می‌دهیم از چیزی که کاربر
 * در عمل می‌پردازد بیشتر نباشد.
 */
export function coinsAsToman(coins: number): number {
  const best = PACKAGES.reduce((a, p) => Math.min(a, p.price / p.coins), Infinity);
  return Math.round((coins * best) / 1_000) * 1_000;
}

/** «۶۳۰ سکه (حدود ۵۷ هزار تومان)» */
export function fmtCoinsWithToman(coins: number): string {
  return `${fmtCoins(coins)} <i>(حدود ${fmtToman(coinsAsToman(coins))})</i>`;
}

export function fmtToman(price: number): string {
  return `${faGroup(price)} تومان`;
}
