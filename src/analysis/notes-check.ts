/**
 * جزوه را در برابر رونوشت می‌سنجد: چه چیزی نوشته شده که در کلاس گفته نشده؟
 *
 * ## چرا این سنجه لازم است
 *
 * نکته‌ها و چک‌لیست هر کدام یک دروازهٔ راستی‌آزمایی دارند — نقل‌قول باید در
 * رونوشت پیدا شود. **جزوه هیچ دروازه‌ای ندارد**، در حالی که بزرگ‌ترین خروجی
 * محصول است و همان چیزی است که کاربر نگه می‌دارد و برای گروه درس فوروارد
 * می‌کند. پرامپت ده جا می‌گوید «از دانشِ خودت چیزی اضافه نکن» و هیچ‌چیز
 * اجرایش نمی‌کند.
 *
 * و شکلِ شکست قابل پیش‌بینی است: مدل نامِ ناقصی را که استاد گفته «کامل»
 * می‌کند. استاد می‌گوید «دکتر صفایی» و جزوه می‌نویسد «دکتر سید علی صفایی» —
 * چون مدل آن نام را می‌داند. دانشجو آن را حرفِ استاد می‌خواند، و روی
 * جزئیاتی حساب می‌کند که در کلاس گفته نشده. همین برای تاریخ و عدد هم رخ
 * می‌دهد و آنجا بهایش بیشتر است.
 *
 * ## چه چیزی را می‌گیرد و چه چیزی را نه
 *
 * سه دسته: نامِ بعد از عنوان‌های احترام (دکتر، استاد، آقای، مرحوم)، عددهای
 * سه‌رقمی و بیشتر، و تاریخ‌ها. هر سه دسته «واقعیتِ سختِ قابلِ راستی‌آزمایی»
 * هستند — چیزی که دانشجو رویش حساب باز می‌کند.
 *
 * جمله‌ها و مفاهیم عمداً بیرون‌اند: بازنویسیِ حرف استاد با کلمات دیگر کارِ
 * درستِ جزوه است، پس تطبیق لفظی روی متنِ توضیحی معنا ندارد و اگر تلاش کنیم
 * چیزی جز نویز نمی‌دهد.
 *
 * ⚠️ خروجی فعلاً فقط **هشدار** است و چیزی حذف نمی‌شود. دلیلش در
 * `analyze.ts` آمده: حذفِ خودکار می‌تواند نامی را ببرد که استاد واقعاً گفته
 * و رونویسیِ خودکار غلط نوشته.
 */

import { normalizeFa } from "../util/text.js";

/** عنوان‌های احترام که در فارسی پیش از نام می‌آیند. */
const HONORIFICS = ["دکتر", "استاد", "اقای", "مرحوم"];

/**
 * کلمه‌هایی که بعد از عنوانِ احترام می‌آیند ولی نام نیستند.
 *
 * بدون این فهرست، «استاد گفت که…» به نامِ ادعاییِ «گفت که» تبدیل می‌شد و
 * فهرست هشدارها پر می‌شد از چیزهایی که اصلاً نام نیستند — و هشداری که پر از
 * نویز باشد خوانده نمی‌شود.
 */
const NOT_NAMES = new Set(
  [
    "گفت", "گفته", "میگه", "میگوید", "فرمود", "فرمودند", "اشاره", "توضیح", "تاکید",
    "این", "ان", "همین", "همان", "ما", "خودش", "خود", "درس", "کلاس", "را", "رو", "که",
    "هم", "در", "به", "از", "با", "بر", "و", "یک", "یه", "چند", "بعد", "قبل",
    "معتقد", "میفرماید", "نوشته", "کتاب", "جزوه", "نظر", "دیدگاه", "قول",
    /**
     * قیدها و ربط‌هایی که **بعد از نام** می‌آیند و نام را دنباله‌دار می‌کنند.
     *
     * روی اجرای واقعی، «دکتر کاتوزیان نیز همین را می‌گوید» به نامِ ادعاییِ
     * «کاتوزیان نیز» رسید — نامی که هرگز در هیچ رونوشتی نیست، پس **همیشه**
     * هشدار می‌داد. یک هشدارِ همیشگی همان‌قدر بی‌فایده است که هیچ هشداری،
     * چون خواننده یاد می‌گیرد نادیده‌اش بگیرد.
     */
    "نیز", "هم", "همچنین", "البته", "اما", "ولی", "یعنی", "مثلا", "حتی", "باز",
    "رضوان", "رحمت", "علیه", "قدس", "طاب", "ره",
  ].map((w) => normalizeFa(w)),
);

/** رونوشت به یک رشتهٔ نرمال‌شدهٔ بزرگ — پایهٔ همهٔ مقایسه‌ها. */
export function transcriptText(utterances: { text: string }[]): string {
  return normalizeFa(utterances.map((u) => u.text).join(" "));
}

/**
 * مارک‌داون را به متنِ خالی نزدیک می‌کند، پیش از استخراج نام و عدد.
 *
 * بلوک‌های کد (`tree` و `flow`) و ریاضی بیرون می‌روند: عددِ داخل یک فرمول
 * یا نامِ گرهِ یک درخت، از جای دیگری از همان جزوه آمده و شمردنِ دوباره‌اش
 * فقط هشدارِ تکراری می‌سازد.
 */
function plainOf(markdown: string): string {
  return markdown
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/\$\$[\s\S]*?\$\$/g, " ")
    .replace(/\$[^$\n]*\$/g, " ")
    .replace(/[*_`#>|]/g, " ");
}

/**
 * نامِ بعد از عنوان احترام — **بلندترین** رشتهٔ نام‌مانند، تا سه کلمه.
 *
 * ## چرا بلندترین و نه هر پیشوند
 *
 * دقیقاً همان حالتی که این ماژول برایش ساخته شد: رونوشت «دکتر صفایی» دارد و
 * جزوه «دکتر سید علی صفایی». اگر پیشوندهای کوتاه‌تر را هم نامزد کنیم، فهرست
 * هشدار سه ردیف برای یک ادعا می‌دهد؛ و اگر کوتاه‌ترین را بگیریم، ادعای
 * واقعی («سید علی صفایی») از دست می‌رود. پس یک نامزد به ازای هر عنوان:
 * بلندترین چیزی که استاد ممکن بود گفته باشد.
 *
 * سقفِ سه کلمه از روی «سید علی صفایی» آمده. بیشتر از آن، نیم‌جمله می‌شود.
 *
 * جدا‌کردن بندها روی نقطه‌گذاریِ **خام** انجام می‌شود، پیش از `normalizeFa`:
 * آن تابع نقطه و ویرگول را به فاصله تبدیل می‌کند، پس بعد از آن دیگر معلوم
 * نیست جمله کجا تمام شده و «استاد گفت. علی هم…» به نامِ «گفت علی» می‌رسید.
 */
const NAME_MAX_WORDS = 3;

function nameCandidates(plain: string): string[] {
  const out: string[] = [];
  for (const clause of plain.split(/[.،,؛;:!؟?()\[\]«»\n\r—–…]+/)) {
    const words = normalizeFa(clause).split(" ").filter(Boolean);
    for (let i = 0; i < words.length; i++) {
      if (!HONORIFICS.includes(words[i]!)) continue;
      const parts: string[] = [];
      for (let k = 1; k <= NAME_MAX_WORDS; k++) {
        const w = words[i + k];
        if (!w || NOT_NAMES.has(w) || w.length < 3 || /^\d/.test(w)) break;
        parts.push(w);
      }
      if (parts.length) out.push(parts.join(" "));
    }
  }
  return out;
}

/** عددِ سه‌رقمی و بیشتر، و تاریخ‌های عددی. */
function numberCandidates(plain: string): string[] {
  const norm = normalizeFa(plain);
  const nums = norm.match(/\d{3,}/g) ?? [];
  // تاریخ به هر سه شکلِ رایج: ۱۴۰۵/۰۶/۱۳ و ۱۴۰۵-۰۶-۱۳ و ۱۳ آذر
  const dates = norm.match(/\d{1,4}\s*[\/\-]\s*\d{1,2}\s*[\/\-]\s*\d{1,4}/g) ?? [];
  return [...nums, ...dates];
}

/**
 * چیزهایی که جزوه ادعا کرده و در رونوشت نیستند.
 *
 * `transcriptNormalized` باید از قبل با `normalizeFa` گذشته باشد — همان
 * رشته‌ای که `transcriptText` می‌سازد. مقایسه روی **مرزِ کلمه** است، وگرنه
 * عددِ «۱۸۳» داخل «۱۸۳۰» پیدا می‌شد و ادعای غلط تأیید می‌گرفت.
 */
export function unsupportedMentions(notesMarkdown: string, transcriptNormalized: string): string[] {
  if (!notesMarkdown.trim()) return [];
  const hay = ` ${transcriptNormalized} `;
  /**
   * نسخهٔ **بی‌فاصله** از رونوشت، برای نامی که جدا یا سرِهم نوشته می‌شود.
   *
   * روی اجرای واقعی، هفت هشدار از یک جلسه درآمد و تقریباً همه‌شان از همین
   * بودند: رونوشت «ملا حسین قلی همدانی» نوشته بود و جزوه «ملا حسینقلی
   * همدانی». هر دو یک نام‌اند و استاد واقعاً گفته بودش — ولی مقایسهٔ
   * کلمه‌به‌کلمه آن را «ادعای بی‌ریشه» می‌دید.
   *
   * `normalizeFa` نیم‌فاصله را حذف می‌کند ولی فاصلهٔ عادی را نه، و رونویسیِ
   * خودکار دقیقاً همین‌جا بی‌ثبات است. با حذفِ همهٔ فاصله‌ها در یک نسخهٔ
   * موازی، هر دو صورت به یک رشته می‌رسند.
   *
   * این فقط **پوشش** می‌دهد و هرگز هشدار اضافه نمی‌کند: نامی که در هیچ‌کدام
   * از دو صورت پیدا نشود، همچنان گزارش می‌شود.
   */
  const squeezed = transcriptNormalized.replace(/\s+/g, "");
  const plain = plainOf(notesMarkdown);

  const seen = new Set<string>();
  const out: string[] = [];

  const consider = (candidate: string) => {
    const c = candidate.trim();
    if (!c || seen.has(c)) return;
    seen.add(c);
    if (hay.includes(` ${c} `)) return;
    /**
     * همان نام، سرِهم‌نوشته — «حسینقلی» در برابر «حسین قلی».
     *
     * فقط برای **نام**، و این قید حیاتی است: مقایسهٔ بی‌فاصله مرزِ کلمه را
     * از بین می‌برد، پس روی عدد فاجعه است — «۱۸۳» داخل «۱۸۳۰» پیدا می‌شود و
     * یک ادعای کاملاً تازه «تأییدشده» حساب می‌شود. برای نام بی‌خطر است چون
     * حروف فارسی این‌طور تصادفی داخل هم نمی‌افتند، و همان‌جاست که رونویسیِ
     * خودکار بی‌ثبات است.
     */
    if (/\p{L}/u.test(c) && squeezed.includes(c.replace(/\s+/g, ""))) return;
    out.push(c);
  };

  /**
   * نامِ کوتاه‌ترِ موجود در رونوشت، نامِ بلندترِ شاملش را **توجیه نمی‌کند**.
   *
   * «دکتر صفایی» در رونوشت هست و «سید علی صفایی» در جزوه؛ دومی همچنان یک
   * ادعای تازه است، حتی اگر یک کلمه‌اش گفته شده باشد. پس نامزد به‌صورت
   * کامل سنجیده می‌شود، نه کلمه‌به‌کلمه.
   */
  for (const n of nameCandidates(plain)) consider(n);
  for (const n of numberCandidates(plain)) consider(n);

  return out;
}
