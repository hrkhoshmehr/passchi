import { z } from "zod";

/**
 * شاهد (منبع).
 *
 * نقل‌قول عمداً کوتاه است: خواننده می‌خواهد در یک نگاه ببیند استاد چه گفته،
 * نه اینکه یک پاراگراف بخواند. متن کامل در رونوشت هست و زمانش هم اینجاست.
 */
export const Evidence = z.object({
  quote: z
    .string()
    .describe("کوتاه‌ترین بریدهٔ عیناً نقل‌شده که ادعا را ثابت کند — حداکثر ۱۵ کلمه."),
  at_ms: z.number().int().describe("زمان شروع همان جمله بر حسب میلی‌ثانیه."),
  speaker: z.enum(["استاد", "دانشجو", "نامشخص"]),
});
export type Evidence = z.infer<typeof Evidence>;

export const SegmentKind = z.enum([
  "teaching", // تدریس محتوای درسی
  "qa", // پرسش و پاسخ
  "admin", // حضور و غیاب، نمره، اطلاعیه
  "offtopic", // حاشیه
  "technical", // مشکل فنی
  "break", // استراحت یا وقفه
]);
export type SegmentKind = z.infer<typeof SegmentKind>;

/** یک نقطهٔ داخل یک بخش: «دقیقهٔ ۱۲، حل تمرین دوم». */
export const ChapterPart = z.object({
  at_ms: z.number().int(),
  label: z.string().describe("حداکثر ۸ کلمه"),
});

/**
 * بخش‌های درشتِ کلاس.
 *
 * نسخهٔ قبلی خط زمانی ریز می‌داد — گاهی سی ردیف — و کسی سی ردیف را نمی‌خواند.
 * حالا چند بخش درشت که در یک نگاه دیده می‌شوند، و ریزه‌کاری هرکدام داخل
 * `parts` جمع می‌شود تا فقط اگر کاربر خواست بازش کند.
 */
export const Chapter = z.object({
  start_ms: z.number().int(),
  end_ms: z.number().int(),
  kind: SegmentKind,
  title: z.string().describe("حداکثر ۶ کلمه — این بخش دربارهٔ چه بود"),
  parts: z
    .array(ChapterPart)
    .describe("۰ تا ۵ نقطهٔ داخل همین بخش، به ترتیب زمان. بخش کوتاه لازم نیست زیربخش داشته باشد."),
});

/**
 * چک‌لیست، **بدون دستهٔ «سایر»**.
 *
 * «سایر» درِ فراری بود که در ۱۲ جلسه از ۲۷ جلسهٔ واقعی باز شد و هیچ‌بار چیز
 * تازه‌ای از آن بیرون نیامد: شش بار تشریفاتِ آغاز و پایان («استاد جلسه را با
 * دعا آغاز کرد»)، چهار بار بازگوییِ همان چیزی که در سرخط و روایت جلسه هست
 * («استاد به بیان مباحث نظری پرداخت»)، و دو بار واقعیتی که برچسبش غلط بود و
 * جایش در نکته‌ها بود («تأکید بر تهیهٔ کتاب قانون»).
 *
 * پرامپت از قبل صریح گفته بود «سایر را فقط وقتی به کار ببر که هیچ دستهٔ
 * دیگری نمی‌خورد» و باز همین شد؛ یعنی مسئله بی‌دقتیِ مدل نبود، خودِ وجودِ
 * ردیفِ خالی بود — مدل آن را تعهدی می‌بیند که باید پرش کند، و وقتی چیزی برای
 * گفتن نیست خلاصهٔ کلاس را دوباره می‌نویسد.
 *
 * حذفش **کنترل‌شده** است، نه تنگ‌کردن دامنه: هم‌زمان دو دستهٔ «منبع» و
 * «راه ارتباطی» به نکته‌ها اضافه شدند تا آنچه واقعاً بی‌خانه بود خانه پیدا
 * کند. کارِ ناشناخته در لایهٔ ترمیم حذف می‌شود، نه اینکه دوباره به «سایر»
 * برگردد.
 */
export const ProfessorAction = z.object({
  action: z.enum([
    "attendance",
    "quiz",
    "homework",
    "deadline",
    "exam_info",
    "grading",
    "makeup_class",
    "class_cancelled",
  ]),
  happened: z.boolean(),
  // شاهد **پیش از** توضیح، به همان دلیلی که در KeyPoint آمده: تا جملهٔ واقعی
  // اول برداشته شود و توضیح از روی آن نوشته شود، نه برعکس.
  evidence: Evidence.nullable(),
  detail: z.string().describe("یک جملهٔ کوتاه. توضیح اضافه نده."),
});

/**
 * چیزی که دانشجو **باید بداند**.
 *
 * دامنه عمداً باریک است، ولی نه باریک‌تر از واقعیت. معیار این است: اگر
 * دانشجو این را نداند، یا نمره‌اش کم می‌شود یا سرِ جلسهٔ بعد غافلگیر می‌شود.
 *
 * نوع‌ها یکی‌یکی و هر بار از روی یک شکاف واقعی اضافه شده‌اند، نه از روی یک
 * دسته‌بندیِ ذهنی. «نمره و بارم» و «حواست باشه» آمدند چون «بارم امتحان ۱۲
 * نمره است» و «جلسهٔ بعد کلاس تشکیل نمی‌شود» جایی برای نشستن نداشتند.
 *
 * «منبع» و «راه ارتباطی» هم همین‌طور آمدند. شکافِ منبع روی دادهٔ واقعی
 * اندازه‌گیری شد: چهار دقیقهٔ اولِ جلسهٔ اولِ «حقوق مدنی ۳» فهرست کتاب است —
 * اعمال حقوقی کاتوزیان، حقوق مدنی ۳ شهیدی، دورهٔ پنج‌جلدی — و همان صوت سه بار
 * تحلیل شد: یک بار نام کتاب‌ها زیر برچسب تأکید ماند و **دو بار کاملاً ناپدید
 * شد**، نه در نکته‌ها و نه در جزوه. معرفیِ منبع چون خانهٔ خودش را نداشت بین
 * تکلیف و تأکید سرگردان می‌شد و در دروازهٔ اهمیت می‌مُرد.
 *
 * «راه ارتباطی» هنوز روی دادهٔ ما رخ نداده — هر دو درسِ موجود سخنرانیِ
 * محض‌اند — ولی نبودنش را خودِ مدل نشان داد: یک بار در چک‌لیست نوشت «ساعات
 * دفتر استاد اعلام نشد»، یعنی انتظارش را دارد و خانه‌ای برایش نیست.
 *
 * «تصحیح استاد» از یک زاویهٔ دیگر آمد: کاربرِ این محصول جزوهٔ جلسهٔ قبل را
 * دارد. وقتی استاد می‌گوید «چیزی که هفتهٔ پیش گفتم اشتباه بود»، آن جمله
 * جزوهٔ قبلی را باطل می‌کند و هیچ‌کدام از دسته‌های دیگر آن را نمی‌گیرد —
 * تأکید نیست، تکلیف نیست، ترتیب کلاس هم نیست.
 *
 * «محدودهٔ درس» را همان اجرای آزمایشیِ این تغییرات پیدا کرد: استاد گفت
 * «مباحث این ترم از مادهٔ ۱۸۳ لغایت مادهٔ ۳۰۰ است» و مدل — چون خانه‌ای
 * نداشت — آن را «محدودهٔ مواد امتحانی» نامید و برچسب exam زد. نتیجه بدترین
 * حالتِ ممکن بود: نکته در دروازهٔ اهمیت مُرد، ولی همان ادعای تفسیریِ
 * «امتحانی» از راهِ چک‌لیست به دانشجو رسید. حالا واقعیت، خودش، خانه دارد.
 *
 * قاعدهٔ افزودن دسته همین است و باید همین بماند: دسته وقتی اضافه می‌شود که
 * یک **واقعیتِ بی‌خانه** پیدا شود — و ترجیحاً وقتی که در یک خروجیِ واقعی
 * دیده شده باشد، نه وقتی که دسته‌بندی ناقص به نظر برسد. دستهٔ بی‌مصداق همان
 * «سایر» است با اسمی محترمانه‌تر.
 */
export const KeyPoint = z.object({
  /**
   * **نقل‌قول اول می‌آید، و این مهم‌ترین تصمیمِ ترتیبی در این شیء است.**
   *
   * مدل فیلدها را به همین ترتیب می‌نویسد. تا وقتی evidence آخر بود، مدل اول
   * ادعا را می‌ساخت («استاد بر مطالعهٔ منابع اصلی تأکید کرد») و بعد دنبال
   * جمله‌ای می‌گشت که آن ادعا را بپوشاند — یعنی دقیقاً مسیرِ ساختنِ نقل‌قول:
   * چسباندن دو خط به هم، یا بازنویسیِ حرف استاد با کلمات خودش. هر دو در
   * دروازهٔ راستی‌آزمایی می‌میرند و نکته کلاً حذف می‌شود.
   *
   * حالا برعکس است: اول یک جملهٔ **واقعی** از رونوشت برداشته می‌شود و بعد
   * روی همان جمله برچسب و عنوان و توضیح نوشته می‌شود. ادعا از دلِ شاهد
   * درمی‌آید، نه شاهد از دلِ ادعا.
   */
  evidence: Evidence.describe("اجباری — نکتهٔ بدون نقل‌قول اصلاً برنگردانده نشود."),
  kind: z.enum([
    "exam", // استاد گفته در امتحان می‌آید
    "grading", // بارم، روش نمره‌دهی، سهم حضور و کوییز و پروژه
    "deadline", // مهلت
    "homework", // هر کاری بیرون از کلاس: تمرین، خواندن فصل، تهیه و مطالعهٔ منبع
    "logistics", // ترتیبِ خودِ کلاس: چه همراه بیاور، ساعت عوض شد، جلسهٔ بعد نیست
    "syllabus", // محدودهٔ درس در این ترم: از کجا تا کجا، کدام فصل‌ها
    "resource", // منبعی که استاد معرفی کرد: کتاب، جزوه، مقاله، سامانه
    "contact", // راه رسیدن به استاد یا دستیار: ساعت حضور، ایمیل، گروه
    "correction", // حرف جلسهٔ قبل یا همین جلسه را پس گرفت یا اصلاح کرد
    "emphasis", // آخرین گزینه: مبحثی *درسی* که استاد صریحاً گفته مهم است
  ]),
  title: z.string().describe("حداکثر ۸ کلمه — همان چیزی که دانشجو باید بخواند"),
  detail: z
    .string()
    .describe(
      "توضیح کامل همین مورد بر پایهٔ چیزی که در کلاس گفته شد: دقیقاً چه باید بکند، " +
        "کدام بخش یا کدام تمرین، با چه شرطی. نامِ کامل کتاب و نویسنده، نشانی سامانه، " +
        "ساعت و روز. دو تا چهار جمله. اگر جزئیاتی گفته نشده، رشتهٔ خالی.",
    ),
  due: z.string().nullable().describe("مهلت، عیناً همان‌طور که استاد گفته. اگر نگفته null."),
});

/** سرفصل: عنوان و دقیقه. جزئیاتش در جزوه می‌آید، نه اینجا. */
export const Topic = z.object({
  title: z.string().describe("حداکثر ۸ کلمه"),
  start_ms: z.number().int(),
  end_ms: z.number().int(),
  /** برای ساخت جزوه لازم است، ولی در پیام تلگرام نمایش داده نمی‌شود */
  summary: z.string().describe("یک جمله"),
  terms: z.array(z.string()),
});

export const GlossaryEntry = z.object({
  term: z.string(),
  english: z.string().nullable(),
  definition: z.string().describe("یک جمله"),
});

export const ClassAnalysis = z.object({
  session_title: z.string().describe("عنوان جلسه، حداکثر ۸ کلمه"),
  course_guess: z.string().nullable(),
  headline: z.string().describe("یک جمله: در این کلاس چه گذشت"),
  class_recap: z
    .string()
    .describe(
      "تعریف‌کردن کلاس برای هم‌کلاسیِ غایب، با لحن دوستانه و روایی: چهار تا هفت جمله " +
        "که به ترتیب بگوید کلاس چطور گذشت. یک پاراگراف پیوسته، بدون بولت و بدون تیتر.",
    ),
  /**
   * ترتیب فیلدها اینجا **معنا دارد** و اتفاقی نیست.
   *
   * مدل با `response_format` به همان ترتیبی می‌نویسد که در اسکیما آمده. وقتی
   * `chapters` پنجمین فیلد بود، مدل باید مرزهای زمانی یک کلاس ۹۴ دقیقه‌ای را
   * بدهد پیش از آنکه فرصت کرده باشد کل رونوشت را ببیند — و نتیجه‌اش همان
   * خطای «همهٔ مرزها زیر ده دقیقه» بود که در سه اجرا از هشت تکرار شد.
   *
   * حالا `topics` جلوتر می‌آید: مدل اول سرفصل‌ها را به ترتیب زمانی می‌شمارد
   * (که مجبورش می‌کند تا انتهای رونوشت برود) و بعد از روی همان‌ها بخش‌های
   * درشت را می‌بُرد.
   *
   * و به همین دلیل `professor_actions` **بعد از** `key_points` آمد.
   * پیش‌تر جلوتر بود، یعنی مدل به «تکلیف نداد» متعهد می‌شد پیش از آنکه به
   * فهرست نکته‌ها برسد و همان‌جا تکلیف را پیدا کند. در پنج جلسهٔ واقعی
   * دقیقاً همین شد: چک‌لیست گفت «تکلیفی نداد» و چند خط پایین‌تر یک موردِ
   * تأییدشده می‌گفت استاد خواسته کتاب قانون را تهیه کنند. حالا چک‌لیست
   * **جمع‌بندیِ** چیزی است که مدل همین الان نوشته، نه یک حدس مستقل.
   */
  topics: z.array(Topic),
  chapters: z
    .array(Chapter)
    .describe("۴ تا ۶ بخش درشت که پشت سر هم کل صوت را بپوشانند؛ بخش آخر باید در نیمهٔ دوم صوت شروع شود"),
  key_points: z.array(KeyPoint),
  professor_actions: z.array(ProfessorAction),
  glossary: z.array(GlossaryEntry),
  open_questions: z.array(z.string()).describe("بخش نامفهوم صوت یا سؤال بی‌جواب"),
  next_session_hint: z.string().nullable(),
});
export type ClassAnalysis = z.infer<typeof ClassAnalysis>;

// ── نتیجهٔ نهایی پس از راستی‌آزمایی ───────────────────────────────────────

export interface VerifiedEvidence extends Evidence {
  verified: boolean;
  score: number;
}

export interface TimelineStats {
  kind: SegmentKind;
  ms: number;
  pct: number;
}

/**
 * سقف نکته‌ها — **در کد اعمال می‌شود، نه در پرامپت**.
 *
 * تا وقتی انتخابِ «کدام هشت‌تا» با مدل بود، دو اجرا روی یک صوت دو فهرست
 * می‌دادند. حالا سقف بعد از دروازه‌ها و با ترتیبِ نمایش اعمال می‌شود.
 */
export const MAX_KEY_POINTS = 8;

/**
 * ترتیب نمایش نکته‌ها، بر اساس «چقدر فوری است».
 *
 * اول چیزهایی که مهلت یا اقدام دارند، بعد اطلاعات نمره، و آخر تأکیدهای درسی
 * که فوریت ندارند. اینجا نشسته چون هم تحلیل (برای اعمال سقف) و هم نمایش به
 * آن نیاز دارند و دو نسخه شدنش یعنی سقف چیزی را ببُرد که کاربر بالای فهرست
 * می‌بیند.
 */
const KEY_POINT_ORDER: Record<string, number> = {
  exam: 0, deadline: 1, homework: 2, logistics: 3, grading: 4,
  // تصحیح بالا می‌نشیند چون جزوهٔ جلسهٔ قبلِ دانشجو را باطل می‌کند؛ منبع و
  // راه ارتباطی اقدامِ فوری نمی‌خواهند ولی اطلاعاتِ سختِ ترم‌اند (اسم کتاب،
  // ساعت دفتر) — پس بالاتر از تأکیدهای درسی می‌نشینند.
  correction: 5, syllabus: 6, resource: 7, contact: 8, emphasis: 9,
};

/**
 * توصیه ده رتبه پایین‌تر از همتای اجباری‌اش می‌نشیند: کاری که استاد خواسته
 * همیشه باید بالاتر از کاری باشد که فقط پیشنهاد کرده — و اگر سقف قرار است
 * چیزی را ببُرد، اول توصیه‌ها بریده شوند.
 */
export function keyPointRank(kind: string, obligation?: string): number {
  return (KEY_POINT_ORDER[kind] ?? 9) + (obligation === "recommended" ? 10 : 0);
}

export interface AnalysisReport extends Omit<ClassAnalysis, "key_points" | "professor_actions"> {
  key_points: Array<
    Omit<z.infer<typeof KeyPoint>, "evidence"> & {
      evidence: VerifiedEvidence;
      /**
       * از روی نقل‌قولِ تأییدشده حساب می‌شود، نه از مدل. نبودنش (گزارش‌های
       * قدیمیِ بایگانی) یعنی «اجباری» — همان رفتار پیش از این تغییر.
       */
      obligation?: "required" | "recommended";
    }
  >;
  professor_actions: Array<
    Omit<z.infer<typeof ProfessorAction>, "evidence"> & { evidence: VerifiedEvidence | null }
  >;
  /** درصدهای *محاسبه‌شده* از خط زمانی — نه حدس مدل */
  composition: TimelineStats[];
  silenceMs: number;
  droppedCitations: number;
  /** تفکیکِ همان عدد، برای اینکه بشود فهمید کدام دروازه چه چیزی را کشت. */
  droppedUnverified: number;
  droppedImportance: number;
  demotedActions: number;
}
