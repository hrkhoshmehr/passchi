/**
 * پیام پایانیِ تور.
 *
 * سه کار می‌کند و ترتیبش عمدی است: اول می‌گوید بالا نمونه بود (وگرنه کاربر
 * فکر می‌کند جلسهٔ خودش پردازش شده)، بعد دعوت می‌کند صوت خودش را بفرستد، و
 * آخر راه ارتباط با پشتیبانی را می‌دهد.
 *
 * **از سکهٔ هدیه حرفی نمی‌زند.** بیست سکه یک کلاس کامل نمی‌خرد و وعده‌دادنش
 * در همین لحظه — درست بعد از دیدن یک تحلیل کامل — انتظاری می‌سازد که
 * برآورده نمی‌شود. موجودی در صفحهٔ حساب دیده می‌شود؛ همان‌جا جای درستش است.
 */
export function outroMessage(supportUsername: string): string {
  const out = [
    "☝️ <b>چیزایی که بالا دیدی، خروجیِ صوت یه کلاس واقعی بود.</b>",
    "",
    "<b>حالا نوبت خودته.</b> صوت کلاستو بفرست تا همینا رو برات دربیارم.",
  ];
  if (supportUsername) {
    out.push("", `❓ سوالی داشتی، به @${supportUsername} پیام بده.`);
  }
  return out.join("\n");
}
