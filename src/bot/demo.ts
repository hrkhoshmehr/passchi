/**
 * صوت نمونه، با `file_id` تلگرام.
 *
 * **بدون این، تور نمونه ناقص است.** تلگرام زمان‌های `MM:SS` را فقط وقتی به
 * لینک پخش تبدیل می‌کند که پیام، ریپلایِ یک پیام صوتی در *همان چت* باشد. تا
 * وقتی صوت را نفرستیم، «۰۷:۲۴» فقط یک عدد است و کاربر نمی‌تواند امتحانش کند
 * — یعنی همان قابلیتی که در پیام خوش‌آمد وعده‌اش را داده‌ایم، در خودِ نمونه
 * کار نمی‌کند.
 *
 * **`file_id` به تفکیک سکو، نه یک مقدار.** نسخهٔ اول یک `file_id` تلگرام بود
 * که روی بله بی‌معناست — و چون ارسال صوت آنجا شکست می‌خورد، کاربر بله توری
 * می‌دید بدون صوت. حالا هر سکو شناسهٔ خودش را دارد و از `.env` می‌آید:
 * `SAMPLE_AUDIO_FILE_ID` برای تلگرام و `SAMPLE_AUDIO_FILE_ID_BALE` برای بله.
 *
 * چرا `.env` و نه مخزن: خودِ فایل ۱۶ مگابایت است و جای یک باینری با این
 * اندازه در تاریخچهٔ git نیست. یک بار دستی فرستاده می‌شود و شناسه‌اش می‌ماند.
 *
 * ⚠️ شناسه به توکن ربات گره خورده است. با عوض‌شدن توکن باید دوباره گرفته شود.
 * اگر خالی بماند صوت فرستاده نمی‌شود و بقیهٔ تور سالم جلو می‌رود — پس تور
 * ناقص می‌شود ولی نمی‌شکند.
 */
export function sampleAudioFileId(platform: string): string | null {
  const id = platform === "bale" ? config.SAMPLE_AUDIO_FILE_ID_BALE : config.SAMPLE_AUDIO_FILE_ID;
  return id || null;
}

