/**
 * تور نمونه برای کاربر تازه.
 *
 * مسئله‌ای که این ماژول حل می‌کند: کاربر تازه نمی‌داند خروجی چه شکلی است.
 * توصیف‌کردنش کار نمی‌کند — «خلاصهٔ کلاس با ذکر منبع» برای کسی که ندیده،
 * یک ادعای تبلیغاتی است مثل هر ادعای دیگر. تنها راهِ فهماندن، **نشان‌دادن**
 * است.
 *
 * پس یک جلسهٔ واقعی — `class example.m4a`، جلسهٔ اول «حقوق مدنی ۳» به طول
 * ۹۴ دقیقه — یک بار از خط لولهٔ واقعی گذشته و خروجی‌اش اینجا ذخیره شده.
 * کاربر تازه دقیقاً همان چیزی را می‌بیند که اگر خودش صوت می‌فرستاد می‌گرفت،
 * **به‌علاوهٔ خودِ صوت** تا زمان‌ها واقعاً قابل کلیک باشند.
 *
 * دو قاعده که در پیاده‌سازی رعایت شده‌اند:
 *
 * **۱) هیچ‌چیز ساختگی نیست.** این خروجی از مدل واقعی روی صوت واقعی آمده و
 * نقل‌قول‌هایش از همان دروازهٔ `verifyQuote` گذشته‌اند. اگر نمونه را دستی
 * قشنگ کنیم، اولین جلسهٔ خودِ کاربر ناامیدکننده می‌شود — و آن بدترین لحظهٔ
 * ممکن برای ناامیدی است.
 *
 * **۲) مرحله‌به‌مرحله، نه یک‌جا.** ده پیام پشت‌سرهم پس از `/start` کاربر را
 * فراری می‌دهد. هر گام پشت یک دکمه است، پس کاربر خودش جلو می‌رود و هر لحظه
 * می‌تواند بایستد.
 */

