export function stepKeyboard(next: string, label: string): InlineKeyboard {
  return new InlineKeyboard().text(label, next);
}

/**
 * پیام پایانیِ تور.
 *
 * سه کار می‌کند و ترتیبش عمدی است: اول می‌گوید بالا نمونه بود (وگرنه کاربر
 * فکر می‌کند جلسهٔ خودش پردازش شده)، بعد دعوت می‌کند صوت خودش را بفرستد، و
 * آخر راه ارتباط با پشتیبانی را می‌دهد.
 *
 * دربارهٔ سهمیهٔ رایگان **دقیق** حرف می‌زند: آن ۱۵ دقیقه برای سنجیدن
 * «دقت صوت به متن» است، نه یک جلسهٔ کامل رایگان. کاربری که این را نداند و
 * انتظار جزوهٔ کامل داشته باشد، ناامید می‌شود — و انتظارِ اشتباه را خودمان
 * ساخته‌ایم.
 */
export function outroMessage(freeMinutes: number, supportUsername: string): string {
  const out = [
    "☝️ <b>چیزایی که بالا دیدی، خروجیِ صوت یه کلاس واقعی بود.</b>",
    "",
    "<b>حالا نوبت خودته.</b> صوت کلاستو بفرست تا همینا رو برات دربیارم.",
    "",
    `🎁 <b>یه صوت تا ${toFaDigits(freeMinutes)} دقیقه رایگان برات پیاده می‌کنم</b> — ` +
      "تا با گوش خودت بسنجی چقدر دقیق می‌شنوم. اصطلاح‌های تخصصی درس خودت، لهجهٔ استادت، " +
      "کیفیت ضبط گوشیت؛ اینا رو فقط روی صوت خودت می‌شه فهمید.",
    "",
    `<i>اون ${toFaDigits(freeMinutes)} دقیقه فقط متنِ کلاسه. خلاصه و نکته‌های امتحانی و جزوه — ` +
      "همونایی که بالا دیدی — سکه می‌خواد.</i>",
  ];
  if (supportUsername) {
    out.push("", `❓ سوالی داشتی، به @${supportUsername} پیام بده.`);
  }
  return out.join("\n");
}
