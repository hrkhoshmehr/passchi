/**
 * صفحه‌کلید اصلی.
 *
 * اگر `PUBLIC_URL` تنظیم باشد، یک دکمهٔ **مینی‌اپ** هم اضافه می‌شود که همان
 * سایت را داخل تلگرام یا بله باز می‌کند. بدون آن آدرس، دکمه ساخته نمی‌شود:
 * هر دو سکو برای مینی‌اپ HTTPS اجبار می‌کنند و دکمه با آدرس نامعتبر یا
 * ساخته نمی‌شود یا صفحهٔ سفید باز می‌کند — بدتر از نبودنش.
 */
export const mainKeyboard = (() => {
  /**
   * «ارسال صوت» یک دکمهٔ **متنی** است، نه مینی‌اپ.
   *
   * چون دو راه برای رساندن صوت هست و کدام‌یک بهتر است به کاربر بستگی دارد:
   * اگر فایل از قبل در همان پیام‌رسان باشد، فوروارد سریع‌ترین راه است و
   * هیچ بایتی آپلود نمی‌شود. مینی‌اپ برای فایلی است که در گوشی است.
   *
   * پس این دکمه راهنما را نشان می‌دهد و **دکمهٔ آپلود داخل آن پیام** است.
   * اگر مستقیم مینی‌اپ باز می‌شد، کاربری که فقط می‌خواست فوروارد کند هم
   * به آپلود می‌افتاد.
   */
  return new Keyboard()
    .text(BTN.send).text(BTN.history).row()
    .text(BTN.account).text(BTN.courses).row()
    .text(BTN.how).text(BTN.support)
    .resized()
    .persistent();
})();

/** برچسب دکمه → کاری که باید انجام شود. برای مسیریابی پیام‌های متنی. */
export type MenuAction = keyof typeof BTN;

export function menuActionOf(text: string): MenuAction | null {
  const t = text.trim();
  for (const [key, label] of Object.entries(BTN)) {
    if (t === label) return key as MenuAction;
  }
  return null;
}

