/**
 * صفحهٔ پشتیبانی — با راهی که واقعاً کار می‌کند.
 *
 * دو اشکال داشت. آیدی وسطِ جملهٔ فارسی بود و روی گوشی جابه‌جا چیده می‌شد؛
 * حالا خطِ خودش را دارد تا با یک لمس کپی شود. و وقتی آیدی تنظیم نبود
 * می‌گفت «همین‌جا بنویس تا بررسی شود» — در حالی که هیچ دست‌کدی متنِ آزاد را
 * به ادمین نمی‌رساند؛ یعنی پیامی که به هیچ‌کس نمی‌رسید.
 *
 * **بله:** پیکربندی هیچ آیدیِ پشتیبانیِ بله‌ای ندارد و ساختنِ یکی ممنوع است.
 * آیدیِ موجود همان است که در بله هم نشان داده می‌شد. نامِ سکو عمداً در متن
 * نمی‌آید: این متنِ مشترک است و `test-platform-neutral` جلوی نامِ سکو در آن را
 * می‌گیرد. دکمهٔ `t.me` فقط روی تلگرام ساخته می‌شود (`supportKeyboard`).
 * `platform` برای روزی است که آیدیِ بله‌ای در پیکربندی بیاید.
 */
export function supportMessage(_platform: Platform = "telegram"): string {
  const lines = ["<b>👤 پشتیبانی</b>", ""];
  if (config.SUPPORT_USERNAME) {
    lines.push("هر سؤال یا مشکلی داشتی، به این آیدی پیام بده:", `@${config.SUPPORT_USERNAME}`);
  }
  lines.push(
    ...(config.SUPPORT_USERNAME ? [""] : []),
    `<i>اگه کار یه فایل نشد، پولت خودکار برگشته؛ موجودیت رو تو «${BTN.account}» ببین.</i>`,
  );
  return lines.join("\n");
}

/**
 * دکمهٔ پشتیبانی — **فقط در تلگرام**.
 *
 * آدرس `t.me` داخل بله باز نمی‌شود، و آیدی پشتیبانی هم یک حساب تلگرامی است.
 * پس دکمه‌ای که کاربر بله را به بن‌بست می‌برد بدتر از نبودنش است؛ آنجا همان
 * آیدی در متن پیام می‌آید و کاربر خودش کپی می‌کند.
 */
export function supportKeyboard(platform: Platform = "telegram"): InlineKeyboard | undefined {
  if (!config.SUPPORT_USERNAME || platform !== "telegram") return undefined;
  return new InlineKeyboard().url("پیام به پشتیبانی", `https://t.me/${config.SUPPORT_USERNAME}`);
}

