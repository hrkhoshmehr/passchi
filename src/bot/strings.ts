function sortedKeyPoints(r: AnalysisReport) {
  return [...r.key_points].sort(
    (a, b) =>
      keyPointRank(a.kind, a.obligation) - keyPointRank(b.kind, b.obligation) ||
      a.evidence.at_ms - b.evidence.at_ms,
  );
}

