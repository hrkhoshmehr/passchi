/**
 * شکستی که دانشجو باید **دلیلش** را بداند، نه فقط اینکه «نشد».
 *
 * بیشترِ شکست‌های خط لوله کار خودِ ماست — سرویس رونویسی جواب نداد، خروجیِ
 * تحلیل نخواند — و دانشجو هیچ کاری برایشان از دستش برنمی‌آید؛ برای آن‌ها یک
 * جملهٔ عمومی بس است. ولی سه حالت به **خودِ فایل** برمی‌گردد و دانشجو
 * می‌تواند کاری بکند: صدایی در آن نیست، از سقف بلندتر است، یا اصلاً باز
 * نمی‌شود. اگر همان جملهٔ عمومی را بگیرد، همان فایل را دوباره می‌فرستد و
 * دوباره همان را می‌بیند.
 *
 * چرا یک کلاس و نه تطبیقِ متنِ خطا: متنِ خطا برای لاگ و بایگانی نوشته شده و
 * هر کسی ممکن است روزی عوضش کند؛ تطبیقِ رشته آن روز بی‌صدا به پیامِ عمومی
 * برمی‌گشت. `kind` قراردادی است که عوض‌کردنش کامپایلر را قرمز می‌کند.
 *
 * `message` دست‌نخورده می‌ماند تا لاگ، بایگانی و مسیر وب همان متنی را ببینند
 * که تا امروز می‌دیدند.
 */
export type JobFailureKind = "no_speech" | "too_long" | "unreadable";

export class JobFailure extends Error {
  constructor(
    public readonly kind: JobFailureKind,
    message: string,
  ) {
    super(message);
    this.name = "JobFailure";
  }
}
