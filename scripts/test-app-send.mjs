/**
 * صفحهٔ ارسال صوت در مینی‌اپ — دو بن‌بستی که کاربر در آن گیر می‌کرد.
 *
 * ۱. **درس ساخته نمی‌شد.** انتخابگر درس با `hidden` شروع می‌شد و فقط وقتی
 *    `courses.length > 0` بود باز می‌شد. یعنی کاربر تازه — که هیچ درسی
 *    ندارد — هرگز آن را نمی‌دید و تنها راه ساختن درس رفتن به ربات بود. و
 *    چون یادگیری اصطلاح‌های تخصصی شرطی به `inp.course` است، برای کسی که
 *    همیشه از اپ می‌آمد عملاً هرگز فعال نمی‌شد.
 *
 * ۲. **کاربر دسکتاپ راه بیرون نداشت.** بله روی کامپیوتر مینی‌اپ را داخل
 *    خودش باز نمی‌کند و لینک را به مرورگر سیستم می‌سپارد؛ آنجا `initData`
 *    نیست و ورود خودکار ناممکن است. پیامی که می‌گرفت او را به همان حلقه
 *    برمی‌گرداند.
 *
 * اجرا: npx tsx scripts/test-app-send.mjs
 */
import fs from "node:fs";

const readLf = (p) => fs.readFileSync(p, "utf8").split("\r\n").join("\n");
const html = readLf("public/app.html");
const js = readLf("public/app.js");

let bad = 0;
const check = (label, ok, extra = "") => {
  if (!ok) bad++;
  console.log(`${ok ? "✅" : "❌"} ${label}${extra ? ` — ${extra}` : ""}`);
};

// ─── نشانه‌گذاری ─────────────────────────────────────────────────────────────

check(
  "انتخابگر درس از ابتدا پنهان نیست",
  /<div id="course-pick">/.test(html),
  (html.match(/<div id="course-pick"[^>]*>/) ?? ["پیدا نشد"])[0],
);
check("فرم ساخت درس وجود دارد", html.includes('id="course-new"'));
check("فرم ساخت از ابتدا بسته است", /id="course-new" class="hidden"/.test(html));
for (const id of ["course-name", "course-prof", "course-save", "course-cancel", "course-err"]) {
  check(`عنصر ${id} هست`, html.includes(`id="${id}"`));
}

// ─── رفتار ──────────────────────────────────────────────────────────────────

check("گزینهٔ «درس جدید» در انتخابگر ساخته می‌شود", js.includes('value="new"'));
check("ساختن درس به سرور POST می‌شود", /"\/api\/courses",\s*\{\s*\n?\s*method: "POST"/.test(js));
check("درس تازه پس از ساخته‌شدن انتخاب می‌ماند", /loadCourses\(course\.id\)/.test(js));
check("اسم خالی رد می‌شود", /if \(!name\) return fail/.test(js));

// مهم‌ترین: `new` یک شناسه نیست و نباید به سرور برود
check(
  "مقدار «new» به‌عنوان شناسهٔ درس فرستاده نمی‌شود",
  /picked === "new" \? "" : picked/.test(js),
);

// ─── بن‌بست دسکتاپ ──────────────────────────────────────────────────────────
//
// بله روی کامپیوتر دکمهٔ مینی‌اپ را به مرورگر سیستم می‌سپارد و آنجا هیچ
// `initData` نیست. پیام قبلی می‌گفت «از داخل تلگرام یا بله وارد شو» — یعنی
// همان کاری که کاربر تازه کرده بود و شکست خورده بود.
check("دسکتاپ با ویژگی ورودی تشخیص داده می‌شود، نه User-Agent", js.includes("(hover: hover) and (pointer: fine)"));
check("کاربر دسکتاپ به گوشی ارجاع داده می‌شود", /فقط با گوشی کار می‌کنه/.test(js));
check("قول نسخهٔ کامپیوتر داده می‌شود", /نسخهٔ کامپیوتر بعداً اضافه می‌شه/.test(js));
check(
  "دکمه‌های ربات برای کاربر دسکتاپ پنهان می‌شوند",
  /strandedOnDesktop[\s\S]{0,120}show\(\$\("auth-bots"\), false\)/.test(js),
);
check("عنوان صفحه هم عوض می‌شود", html.includes('id="auth-title"') && js.includes('$("auth-title")'));

// ─── قرارداد با سرور ────────────────────────────────────────────────────────
//
// اپ `{ course: { id } }` می‌خواند؛ اگر سرور شکل پاسخ را عوض کند، درس تازه
// بی‌صدا انتخاب نمی‌شود و کاربر صوتش را بی‌درس می‌فرستد.
const server = readLf("src/web/server.ts");
check(
  "پاسخ سرور همان شکلی است که اپ می‌خواند",
  /json\(res, 200, \{ course: \{ id: c\.id/.test(server),
);

console.log(bad === 0 ? "\nهمه سبز ✅" : `\n${bad} بررسی شکست خورد ❌`);
process.exit(bad === 0 ? 0 : 1);
