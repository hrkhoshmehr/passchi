/**
 * دروازهٔ «ادعای تأکید باید در خودِ نقل‌قول باشد».
 *
 * نمونه‌های «باید رد شود» از خروجی واقعی مدل روی example.mp3 برداشته شده‌اند —
 * جمله‌هایی که واقعاً در کلاس گفته شده بودند ولی هیچ ادعای اهمیتی نداشتند و
 * مدل رویشان برچسب «تأکید استاد» زده بود.
 */
import { statesImportance } from "../src/analysis/analyze.ts";

const shouldPass = [
  "این تیپ سؤال سطح تراز رو خوب یاد بگیرید، تو میان‌ترم هست",
  "اینو خوب یاد بگیرید",
  "این قسمت خیلی مهمه",
  "دقت کنید اینجا رو",
  "یادداشت کنید این فرمولو",
  "این تو امتحان میاد",
  "حتماً بلد باشید",
  "این دو تا نمره داره",
  "روی این تأکید دارم",
  "اینو جدی بگیرید",
];

const shouldFail = [
  "روی این مبنا توصیه‌ای که می‌کردن این است",
  "سیر انسان در سلوک سیر در مراتب مقام نوری پروردگاره",
  "تمام کارهاشون چه در افعال، چه در صفات و حتی چه در توجه به ذات خودشون",
  "انقدر این نفس آرام آرام پاک میشه که گویی خودش داره نور میده",
  "مشتق جهت‌دار در راستای بردار یکه تعریف می‌شود",
  "خب حالا بریم سراغ فصل بعد",
];

let bad = 0;
for (const q of shouldPass) {
  if (!statesImportance(q)) { console.log(`❌ باید می‌پذیرفت: «${q}»`); bad++; }
}
for (const q of shouldFail) {
  if (statesImportance(q)) { console.log(`❌ باید رد می‌کرد: «${q}»`); bad++; }
}
console.log(bad === 0
  ? `✅ هر ${shouldPass.length + shouldFail.length} نمونه درست تشخیص داده شد.`
  : `${bad} نمونه اشتباه.`);
process.exit(bad === 0 ? 0 : 1);
