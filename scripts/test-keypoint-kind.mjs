/**
 * تصحیح نوع نکته بر پایهٔ محتوا.
 *
 * مدل نوع را از **لحن** انتخاب می‌کند نه از محتوا: «کتاب قانون رو حتماً سر
 * جلسه داشته باشید» را چون «حتماً» دارد `emphasis` می‌زند. دو بار پرامپت را
 * صریح‌تر کردیم و باز همین شد، پس تصمیم به کد آمد و این اسکریپت همان کد را
 * با نمونه‌های واقعی می‌سنجد.
 *
 * نمونه‌ها از دو دسته‌اند: جمله‌هایی که باید نوعشان عوض شود، و جمله‌هایی که
 * باید دست‌نخورده بمانند — دستهٔ دوم مهم‌تر است، چون یک تصحیح‌کنندهٔ حریص
 * تأکیدهای درسی را هم می‌بلعد.
 */
import { classifyKeyPointKind } from "../src/analysis/analyze.ts";

const CASES = [
  // ── باید logistics شوند ─────────────────────────────────────────────
  ["کتاب قانون رو حتماً سر جلسه داشته باشید", "همراه داشتن کتاب قانون", "logistics"],
  ["از هفتهٔ بعد ساعت کلاس عوض میشه، ۸ صبح بیاید", "تغییر ساعت کلاس", "logistics"],
  ["جلسهٔ بعد کلاس نداریم، من ماموریتم", "لغو جلسهٔ بعد", "logistics"],
  ["کلاس جبرانی پنج‌شنبه ساعت ۱۰ برگزار میشه", "کلاس جبرانی", "logistics"],
  ["ماشین حساب مهندسی همراهتون باشه", "ابزار لازم", "logistics"],
  ["تا جلسهٔ بعد توی سامانه ثبت نام کنید", "ثبت نام سامانه", "logistics"],

  // ── باید grading شوند ───────────────────────────────────────────────
  ["امتحان پایان ترم ۱۲ نمره‌ست، پروژه ۵ نمره و حضور ۳ نمره", "بارم بندی درس", "grading"],
  ["میان ترم ۸ نمره داره و از چهار فصل اول میاد", "بارم میان ترم", "grading"],
  ["امتحان تستی نیست، تشریحیه", "نوع امتحان", "grading"],
  ["هر کی قانون همراهش نباشه دو نمره کم می‌کنم", "جریمهٔ نداشتن قانون", "grading"],

  // ── باید emphasis بمانند: محتوای درسی‌اند ────────────────────────────
  ["این قضیه رو حتماً یاد بگیرید، پایهٔ همه‌ی بحثاست", "قضیهٔ پایه", null],
  ["درس مدنی ۳ شاید مهم‌ترین درس دوره کارشناسی‌تونه", "اهمیت درس مدنی ۳", null],
  ["رو تعریف عقد خوب دقت کنید", "تعریف عقد", null],
  ["این فرمول رو حفظ کنید", "فرمول کلیدی", null],
];

let bad = 0;
for (const [quote, title, want] of CASES) {
  const got = classifyKeyPointKind(quote, title);
  const ok = got === want;
  if (!ok) bad++;
  const shown = got ?? "emphasis (بدون تغییر)";
  console.log(`  ${ok ? "✅" : "❌"} ${shown.padEnd(24)} ${title}`);
  if (!ok) console.log(`      انتظار: ${want ?? "بدون تغییر"} · «${quote}»`);
}

if (bad) {
  console.error(`\n❌ ${bad} نمونه از ${CASES.length} غلط تشخیص داده شد.`);
  process.exit(1);
}
console.log(`\n✅ هر ${CASES.length} نمونه درست تشخیص داده شد.`);
