/**
 * دروازهٔ اول: «این جمله واقعاً گفته شده؟»
 *
 * نمونه‌ها از خروجی واقعی روی `class example.m4a` برداشته شده‌اند، پس
 * پاره‌گفتارها عین چیزی‌اند که سونیوکس داده و نقل‌قول‌ها عین چیزی‌اند که مدل
 * برگردانده.
 *
 * ## باگی که این آزمون را لازم کرد
 *
 * سنجهٔ قبلی فقط می‌شمرد چند کلمهٔ نقل‌قول *جایی* در متن پیدا می‌شود — بدون
 * ترتیب، بدون مجاورت، و با تطبیق زیررشته‌ای. نتیجه‌اش این بود که یک جملهٔ
 * ساختگی، که تنها کلمهٔ نداشته‌اش «امتحان» بود، نمرهٔ ۰٫۹۰ می‌گرفت و قبول
 * می‌شد — یعنی دقیقاً همان کلمه‌ای که کل ادعا رویش سوار است، تنها کلمه‌ای بود
 * که راستی‌آزمایی نمی‌شد.
 *
 * برای همین دستهٔ «باید رد شود» اینجا مهم‌تر از دستهٔ دیگر است.
 */
import fs from "node:fs";
import { containmentScore, normalizeFa } from "../src/util/text.ts";
import { buildTranscript, verifyQuote } from "../src/stt/transcript.ts";

const THRESHOLD = 0.75;

/** پاره‌گفتارِ واقعی که همهٔ نمونه‌ها با آن سنجیده می‌شوند. */
const UTT = normalizeFa(
  "خب بچه‌ها این قسمت رو که گفتم توی جزوه هست و از اون فصل هم یه چیزایی میاد",
);

const shouldPass = [
  // عین جمله
  "این قسمت رو که گفتم توی جزوه هست",
  // یک کلمهٔ پرکننده در نقل‌قول نیامده — رونوشت خودکار همیشه همه را نگه می‌دارد
  "این قسمت رو گفتم توی جزوه هست",
  // بخش انتهایی جمله
  "از اون فصل هم یه چیزایی میاد",
];

const shouldFail = [
  // ⚠️ همان نمونه‌ای که نسخهٔ قبلی با ۰٫۹۰ می‌پذیرفت. «امتحان» گفته نشده.
  "این رو که گفتم از اون فصل توی امتحان میاد",
  // همان کلمه‌ها، ترتیبِ به‌هم‌ریخته
  "میاد امتحان توی فصل اون از",
  // ادعای نمره، که اصلاً در جمله نیست
  "این قسمت توی جزوه هست و دو نمره داره",
];

let bad = 0;

for (const q of shouldPass) {
  const s = containmentScore(q, UTT);
  if (s < THRESHOLD) {
    console.log(`❌ باید می‌پذیرفت (${s.toFixed(2)}): «${q}»`);
    bad++;
  }
}

for (const q of shouldFail) {
  const s = containmentScore(q, UTT);
  if (s >= THRESHOLD) {
    console.log(`❌ باید رد می‌کرد (${s.toFixed(2)}): «${q}»`);
    bad++;
  }
}

// مرزِ کلمه: «علم» نباید داخل «معلم» پیدا شود.
const substringTrap = containmentScore("علم", normalizeFa("معلم ما"));
if (substringTrap >= THRESHOLD) {
  console.log(`❌ زیررشته پذیرفته شد (${substringTrap.toFixed(2)}): «علم» در «معلم ما»`);
  bad++;
}

// ── نقل‌قولِ دوخته‌شده ────────────────────────────────────────────────────
//
// شایع‌ترین شکلِ شکستِ راستی‌آزمایی: مدل چند خط رونوشت را با «…» به هم
// می‌چسباند تا فهرستی را کامل کند. جملهٔ دوخته‌شده در هیچ پاره‌گفتاری پیدا
// نمی‌شود، پس **کل نکته** حذف می‌شد — در حالی که هر تکه‌اش واقعاً گفته شده.
//
// انتظار: تکهٔ بلندتر تأیید شود، زمان روی همان بنشیند، و مهم‌تر از همه
// `matchedQuote` فقط همان تکه باشد — نه جملهٔ دوخته‌شده. چیزی که تأیید نشده
// نباید در جای «عین حرف استاد» به کاربر نشان داده شود.
const tok = (text, startMs, speaker = "1") => ({
  text,
  start_ms: startMs,
  end_ms: startMs + 3000,
  speaker,
  confidence: 0.99,
});

const t = buildTranscript(
  [
    tok("این دو تا کتاب رو حتماً نگاه بکنید. ", 60_000),
    tok("یکی کتاب اعمال حقوقی دکتر کاتوزیان. ", 90_000),
    tok("کتاب قانون رو حتماً سر جلسه داشته باشید. ", 700_000),
  ],
  { toOriginal: (ms) => ms, skippedMs: 0 },
);

const stitched = "این دو تا کتاب رو حتماً نگاه بکنید… کتاب قانون رو حتماً سر جلسه داشته باشید";
const m = verifyQuote(t, stitched, 60_000);
if (!m.ok) {
  console.log("❌ نقل‌قول دوخته‌شده باید از راه تکه‌ها تأیید می‌شد");
  bad++;
} else if (m.matchedQuote.includes("…")) {
  console.log(`❌ متنِ نمایش‌داده‌شده هنوز دوخته‌شده است: «${m.matchedQuote}»`);
  bad++;
} else if (normalizeFa(m.matchedQuote).length >= normalizeFa(stitched).length) {
  console.log(`❌ تکهٔ تأییدشده باید کوتاه‌تر از جملهٔ دوخته‌شده باشد: «${m.matchedQuote}»`);
  bad++;
}

// جملهٔ دوخته‌شده‌ای که هیچ تکه‌اش گفته نشده، باید همچنان رد شود.
const fakeStitch = verifyQuote(t, "این مبحث توی امتحان میاد… بیست نمره داره", 60_000);
if (fakeStitch.ok) {
  console.log("❌ دوختنِ دو جملهٔ ناگفته نباید از دروازه رد شود");
  bad++;
}
// ── چسباندنِ تکه‌های ریز ─────────────────────────────────────────────────
//
// موتور رونویسی هر مکث را مرز می‌گیرد، پس یک جملهٔ پیوسته به دو سه تکه خرد
// می‌شود و نقل‌قولی که رویشان افتاده نمرهٔ کامل نمی‌گیرد. تکهٔ زیر سی نویسه
// به پاره‌گفتار قبلیِ **همان گوینده** می‌چسبد.
{
  const glued = buildTranscript(
    [
      tok("مباحث مربوط به این ترم، از ماده ۱۸۳ شروع می‌شه. از ماده ۱۸۳ ", 100_000),
      tok("لغایت ", 104_000),
      tok("ماده ۳۰۰. این ترم ما از ماده ۱۸۳ می‌خونیم تا ماده ۳۰۰.", 106_000),
    ],
    { toOriginal: (ms) => ms, skippedMs: 0 },
  );
  if (glued.utterances.length !== 1) {
    console.log(`❌ سه تکهٔ یک گوینده باید یک پاره‌گفتار شوند — شد ${glued.utterances.length}`);
    bad++;
  }
  // اطمینان وزنی است، نه میانگینِ میانگین‌ها
  if (Math.abs(glued.utterances[0].confidence - 0.99) > 0.001) {
    console.log(`❌ اطمینانِ وزنی درست به‌روز نشد: ${glued.utterances[0].confidence}`);
    bad++;
  }

  // تکهٔ ریزِ گویندهٔ دیگر نباید بچسبد — وگرنه حرفِ دانشجو به استاد نسبت داده می‌شود
  const twoSpeakers = buildTranscript(
    [tok("این مبحث رو با هم مرور کنیم و بعد بریم سراغ فصل بعدی.", 0, "1"), tok("بله استاد.", 4_000, "2")],
    { toOriginal: (ms) => ms, skippedMs: 0 },
  );
  if (twoSpeakers.utterances.length !== 2) {
    console.log("❌ تکهٔ ریزِ گویندهٔ دیگر نباید به پاره‌گفتار قبلی بچسبد");
    bad++;
  }
}

// ── روی رونوشتِ واقعیِ کش‌شده ────────────────────────────────────────────
//
// همان جمله‌ای که این تغییر برایش انجام شد: روی سه تکه پخش شده بود و نمرهٔ
// ۰٫۸۰ می‌گرفت. بعد از چسباندن و پنجرهٔ سه‌تایی باید عملاً تطبیقِ کامل باشد.
{
  const CACHE = "data/cache/class example.7c6a57d28c894bfb.soniox.json";
  if (!fs.existsSync(CACHE)) {
    console.log(`⏭️ کشِ ${CACHE} نیست — بررسی روی دادهٔ واقعی رد شد`);
  } else {
    const raw = JSON.parse(fs.readFileSync(CACHE, "utf8"));
    const real = buildTranscript(raw.transcript.tokens, { toOriginal: (ms) => ms, skippedMs: 0 });

    const tiny = real.utterances.filter((u) => u.text.length < 40).length;
    const ratio = tiny / real.utterances.length;
    if (ratio >= 0.1) {
      console.log(`❌ سهم پاره‌گفتارهای ریز هنوز بالاست: ${tiny} از ${real.utterances.length}`);
      bad++;
    }

    const m2 = verifyQuote(
      real,
      "مباحث مربوط به این ترم، از ماده ۱۸۳ شروع می‌شه. از ماده ۱۸۳ لغایت ماده ۳۰۰",
      840_000,
    );
    if (m2.score < 0.95) {
      console.log(`❌ نقل‌قولِ مرزی باید نمرهٔ ≥۰٫۹۵ بگیرد — گرفت ${m2.score.toFixed(2)}`);
      bad++;
    }
  }
}


console.log(
  bad === 0
    ? "✅ همه سبز"
    : `${bad} نمونه اشتباه.`,
);
process.exit(bad === 0 ? 0 : 1);
