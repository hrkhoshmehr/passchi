/**
 * دروازه‌هایی که به **بافت** نگاه می‌کنند، نه فقط به نقل‌قول.
 *
 * ## چرا این دسته جدا شد
 *
 * سه دروازهٔ قبلی (نقل‌قول واقعی است؟ ادعای تأکید در خودش هست؟ نوعش درست
 * است؟) همه روی چند کلمهٔ نقل‌قول کار می‌کنند. ولی بعضی خطاها **بیرونِ**
 * نقل‌قول‌اند و از هر سه بی‌خطر رد می‌شوند:
 *
 * • استاد یک قاعدهٔ نمره‌دهی را مطرح می‌کند تا **ردش کند**. نقل‌قولِ وسطش
 *   کاملاً واقعی است، کلمهٔ «نمره» هم دارد، و به‌عنوان قاعده به دانشجو
 *   می‌رسد — با ذکر دقیقه، که ظاهر مستند هم به آن می‌دهد.
 * • نکتهٔ «محدودهٔ درس» که هیچ مرزی در نقل‌قولش نیست، محدوده‌ای اعلام نکرده.
 *
 * اجرا: npx tsx scripts/test-gates-context.mjs
 */
import {
  isRejectedHypothetical,
  statesImportance,
  checklistExtras,
  classifyKeyPointKind,
  obligationOf,
  notesBudget,
  needsExpansion,
  isCourseLevelImportance,
} from "../src/analysis/analyze.ts";

let bad = 0;
const check = (label, ok, extra = "") => {
  if (!ok) bad++;
  console.log(`${ok ? "✅" : "❌"} ${label}${extra ? ` — ${extra}` : ""}`);
};

// ── ۴) فرضِ ردشده ────────────────────────────────────────────────────────
//
// پاره‌گفتار واقعیِ دقیقهٔ ۱۳:۰۷ از کلاس حقوق مدنی ۳.
const REJECTED = `راست راست اومدن و رفتن که آدم چیزی یاد نمی‌گیره که. حالا بعضی‌ها به زور می‌خوان شما رو وادار کنن که به اینکه قانون بیارید. مثلاً فرض کن بگیم آقا هر کی قانون همراهش نباشه، دو نمره کم می‌کنم مثلاً. خب این زشته دیگه. من دارم توصیه می‌کنم. من دارم می‌گم بیار.`;

check("فرضِ ردشدهٔ «دو نمره کم می‌کنم» گیر افتاد", isRejectedHypothetical(REJECTED));

// و جمله‌ای که واقعاً قاعده است نباید گیر بیفتد
check(
  "بارمِ واقعیِ میان‌ترم گیر نیفتاد",
  !isRejectedHypothetical("میان ترم ۸ نمره داره و از چهار فصل اول میاد. دقت کنید."),
);
check(
  "فرضِ بی‌نفی گیر نیفتاد",
  !isRejectedHypothetical("فرض کنید دو نفر با هم توافق می‌کنند و عقدی می‌بندند. این عقد صحیح است."),
);
check(
  "نفیِ پیش از فرض حساب نمی‌شود",
  !isRejectedHypothetical("من این کار رو نمی‌کنم چون وقت ندارم. حالا فرض کنید عقدی بسته شده."),
);

// ── ۴ب) نفی تا چهار توکن بعد از نشانه ───────────────────────────────────
//
// دو توکن کافی نبود: فارسیِ گفتاری بین نشانه و نفی چیز می‌گذارد.
check("«این قسمت اصلاً برای شما مهم نیست» رد شد", !statesImportance("این قسمت اصلاً برای شما مهم نیست"));
check("«این تو امتحانِ ما اصلاً نمیاد» رد شد", !statesImportance("این تو امتحان ما اصلا نمیاد"));
// ولی نفیِ دور نباید ادعای واقعی را بکشد
check(
  "تأکیدِ واقعی با یک «نه» در ته جمله زنده ماند",
  statesImportance("این قسمت خیلی مهمه، حواستون باشه که جا نمونه"),
);

// ── ۴ج) تأکید روی خودِ درس، نه روی یک مبحث ──────────────────────────────
//
// این سه جمله همه ادعای اهمیت دارند و باید هم از `statesImportance` رد شوند
// (آن تابع کارِ دیگری می‌کند)، ولی هیچ‌کدام مبحثی را نام نمی‌برند — پس به
// دانشجوی غایب چیزی نمی‌گویند و فقط فهرست را پر می‌کنند.
//
// یک دور پرامپت با همین نمونه‌ها صریح شد و **بی‌اثر بود**: روی سنجه، نقض در
// یک اجرا از سه اجرا سر جایش ماند و در اجرای سوم با نقل‌قولی از همان جنس
// برگشت. پس تصمیم به کد آمد.
for (const q of [
  "درس مدنی ۳ شاید مهم‌ترین، اگه نگیم مهم‌ترین، درس دوره کارشناسی‌تونه",
  "لذا درس، درس بسیار مهمیه",
  "این درس رو باید بدانید. باید یاد بگیرید. باید براتون مفهوم باشه",
]) {
  check("تأکیدِ سطحِ درس گیر افتاد: " + q.slice(0, 34), isCourseLevelImportance(q));
}

// و برعکسش مهم‌تر است: تأکیدِ واقعی روی یک مبحث نباید قربانی شود، حتی وقتی
// کلمهٔ «درس» هم در همان جمله باشد.
for (const q of [
  "این قسمت از درس خیلی مهمه",
  "این قضیه رو حتماً یاد بگیرید، پایهٔ همه‌ی بحثاست",
  "ماده ۱۸۳ یکی از مواد کلیدی قانون مدنیه. یه ماده بسیار مهمیه",
  "رو تعریف عقد خوب دقت کنید",
  "این فرمول رو حفظ کنید",
  "این تیپ سؤال سطح تراز رو خوب یاد بگیرید، تو میان‌ترم هست",
  // رونویسی خودکار «میان‌ترم» را گاهی جدا می‌نویسد؛ «ترم» نباید کلمهٔ سطحِ درس
  // حساب شود، وگرنه پیش‌بینی‌کننده‌ترین نکتهٔ ممکن حذف می‌شود.
  "اینو خوب یاد بگیرید، تو میان ترم هست",
  // کلمهٔ «درس» در جمله هست ولی موضوعِ اهمیت یک مبحث است، نه خودِ درس
  "توی این درس، عقد لازم و جایز خیلی مهمه",
]) {
  check("تأکیدِ مبحثی زنده ماند: " + q.slice(0, 34), !isCourseLevelImportance(q));
}

// ── ۵) نشانه‌های تازهٔ تکلیف و توصیه ──────────────────────────────────────
check(
  "«تهیه می‌کنید و مطالعه می‌کنید» تکلیف است",
  classifyKeyPointKind(
    "فرض بر اینه که شما تهیه می‌کنید و مطالعه می‌کنید، که حتماً این کار رو انجام بدید",
    "تهیه و مطالعهٔ منابع",
  ) === "homework",
);
check(
  "«سعی بفرمایید … بخونید» توصیه است",
  obligationOf("سعی بفرمایید یکی دو تا از این کتاب‌ها رو بخونید") === "recommended",
);
check(
  "«سعی کنید حتماً» همچنان اجباری است",
  obligationOf("سعی کنید حتماً تا جلسهٔ بعد این فصل رو بخونید") === "required",
);
check(
  "فعل امریِ بی‌نرم‌کننده اجباری می‌ماند",
  obligationOf("فصل سه رو تا جلسهٔ بعد بخونید") === "required",
);

// ── ۶) آشتی چک‌لیست ──────────────────────────────────────────────────────
check(
  "نکتهٔ نمره با کلمهٔ «میان ترم» ردیفِ امتحان را هم روشن می‌کند",
  checklistExtras("grading", "میان ترم ۸ نمره داره و از چهار فصل اول میاد").includes("exam_info"),
);
check(
  "«جلسهٔ بعد کلاس نداریم» ردیفِ لغو کلاس را روشن می‌کند",
  checklistExtras("logistics", "جلسهٔ بعد کلاس نداریم، من ماموریتم").includes("class_cancelled"),
);
check(
  "«کلاس جبرانی» ردیفِ جبرانی را روشن می‌کند",
  checklistExtras("logistics", "کلاس جبرانی پنج‌شنبه ساعت ۱۰ برگزار میشه").includes("makeup_class"),
);
// و نکته‌ای که هیچ‌کدام را ندارد، ردیف اضافه‌ای روشن نمی‌کند
check(
  "نکتهٔ نمرهٔ بی‌ربط به امتحان ردیفِ اضافه نمی‌سازد",
  checklistExtras("grading", "نمرهٔ حضور سه نمره است").length === 0,
);
check(
  "«کتاب قانون رو بیارید» نه لغو است نه جبرانی",
  checklistExtras("logistics", "کتاب قانون رو حتماً سر جلسه داشته باشید").length === 0,
);

// ── ۸) بازه‌های غیردرسی در بودجه ─────────────────────────────────────────
//
// بخش‌های غیردرسی از جدول بیرون‌اند، ولی بازه‌شان باید **صریح** به مدل گفته
// شود: غیبت از جدول یک اطلاعِ منفی است و مدل نمی‌بیندش.
{
  const min = (m) => m * 60_000;
  const rows = notesBudget([
    { title: "معرفی درس و منابع", kind: "admin", start_ms: 0, end_ms: min(14) },
    { title: "تعریف عقد", kind: "teaching", start_ms: min(14), end_ms: min(40) },
  ]);
  check("بخشِ اطلاعیه سهمی در بودجه ندارد", rows.length === 1 && rows[0].kind === "teaching");
  check("بازهٔ هر بخش هم برمی‌گردد", rows[0].startMs === min(14) && rows[0].endMs === min(40));
}

// ── ۹) تصمیمِ گسترش ──────────────────────────────────────────────────────
check("زیر ۸۰٪ کف، گسترش لازم است", needsExpansion(1500, 2920));
check("۹۵٪ کف کافی است", !needsExpansion(2774, 2920));
check("دقیقاً روی ۸۰٪ گسترش لازم نیست", !needsExpansion(2336, 2920));
check("کفِ صفر هرگز گسترش نمی‌خواهد", !needsExpansion(0, 0));

console.log(bad === 0 ? "\nهمه سبز ✅" : `\n${bad} بررسی شکست خورد ❌`);
process.exit(bad === 0 ? 0 : 1);
