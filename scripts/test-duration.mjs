/**
 * واحدِ مدتی که سکو اعلام می‌کند — ثانیه یا میلی‌ثانیه؟
 *
 * ## باگی که این آزمون نگه می‌دارد
 *
 * یک ویسِ ۴۹ ثانیه‌ای در بله، **۸۲۴ سکه** قیمت خورد. بله مدتِ ویس را به
 * میلی‌ثانیه می‌دهد و تلگرام به ثانیه؛ آن فایل ۴۹٬۴۴۰ میلی‌ثانیه بود و همان
 * عدد به‌جای ثانیه نشست. کاربر «اعتبارت کم است» گرفت و کارش همان‌جا ماند.
 *
 * واحد از **حجم فایل** تشخیص داده می‌شود نه از نام سکو، چون شاهدی نداریم که
 * بله برای همهٔ انواع رسانه یک‌جور رفتار کند — و اگر جایی ثانیه بدهد و ما
 * تقسیم بر هزار کنیم، هزینه هزار برابر **کم‌تر** حساب می‌شود؛ خطایی که سمتِ
 * ضررِ ماست و هیچ کاربری هم از آن شکایت نمی‌کند تا بفهمیم.
 *
 * اجرا: npx tsx scripts/test-duration.mjs
 */
import { declaredDurationSec } from "../src/util/time.ts";
import { costCoins } from "../src/billing/coins.ts";

let bad = 0;
const check = (label, ok, extra = "") => {
  if (!ok) bad++;
  console.log(`${ok ? "✅" : "❌"} ${label}${extra ? ` — ${extra}` : ""}`);
};

// ─── همان ویسی که باگ را لو داد ─────────────────────────────────────────────
//
// اندازه‌گیری‌شده روی فایلِ واقعی: ۳۰۴٬۰۳۸ بایت، ۴۹٫۴۴ ثانیه.
{
  const SIZE = 304_038;
  const r = declaredDurationSec(49_440, SIZE);
  check("ویسِ بله (میلی‌ثانیه) به ثانیه برمی‌گردد", r.sec === 49, `${r.sec}`);
  check("و مطمئن است", r.sure);
  check("هزینه‌اش یک سکه است نه ۸۲۴", costCoins(r.sec) === 1, `${costCoins(r.sec)} سکه`);

  // همان فایل، اگر سکو ثانیه بدهد — نباید دست بخورد
  const s = declaredDurationSec(49, SIZE);
  check("ویسِ تلگرام (ثانیه) دست‌نخورده می‌ماند", s.sec === 49 && s.sure);
}

// ─── کلاسِ بلند: خطرِ برعکس ─────────────────────────────────────────────────
//
// اگر کورکورانه «بله یعنی تقسیم بر هزار» می‌نوشتیم، یک کلاس ۵۲ دقیقه‌ای که
// ثانیه اعلام شده بود سه ثانیه خوانده می‌شد و عملاً رایگان تمام می‌شد.
{
  const SIZE = 24 * 1024 * 1024; // ۲۴ مگابایت، نمونهٔ واقعیِ کلاس ۵۲ دقیقه‌ای
  const asSec = declaredDurationSec(3_102, SIZE);
  check("کلاس ۵۲ دقیقه‌ای با اعلامِ ثانیه درست می‌ماند", asSec.sec === 3_102 && asSec.sure);
  check("و رایگان تمام نمی‌شود", costCoins(asSec.sec) === 52, `${costCoins(asSec.sec)} سکه`);

  const asMs = declaredDurationSec(3_101_946, SIZE);
  check("همان کلاس با اعلامِ میلی‌ثانیه هم درست می‌شود", asMs.sec === 3_102 && asMs.sure);
}

// ─── حالت‌های مرزی ──────────────────────────────────────────────────────────
{
  check("مدتِ صفر یعنی نمی‌دانیم", declaredDurationSec(0, 1000).sec === 0);
  check("مدتِ منفی هم یعنی نمی‌دانیم", declaredDurationSec(-5, 1000).sec === 0);

  // بدون حجم، فقط سقفِ مدت سنجیده می‌شود
  const noSize = declaredDurationSec(49_440, 0);
  check("بی‌حجم، عددِ بیرون از سقف به میلی‌ثانیه خوانده می‌شود", noSize.sec === 49, `${noSize.sec}`);

  // عددی که هیچ تفسیرش جور درنمی‌آید: خام برمی‌گردد ولی مطمئن نیست
  const weird = declaredDurationSec(9, 500 * 1024 * 1024);
  check("تفسیرِ ناممکن، «نامطمئن» علامت می‌خورد", !weird.sure);

  // ویدیوی پرحجم و کوتاه نباید به‌اشتباه میلی‌ثانیه خوانده شود
  const video = declaredDurationSec(600, 300 * 1024 * 1024); // ۳۰۰ مگ، ۱۰ دقیقه ≈ ۴ مگابیت
  check("ویدیوی پرنرخ‌بیت ثانیه می‌ماند", video.sec === 600 && video.sure);
}

console.log(bad === 0 ? "\nهمه سبز ✅" : `\n${bad} بررسی شکست خورد ❌`);
process.exit(bad === 0 ? 0 : 1);
