/**
 * دروازهٔ «پرسش و پاسخ جلسه».
 *
 * دو چیز سنجیده می‌شود و هر دو از یک جنس‌اند: **ادعایی که به دانشجو می‌رسد
 * باید در رونوشت ریشه داشته باشد.**
 *
 * ۱) پاسخی که در صوت گفته نشده، جفت را حذف می‌کند — همان دروازهٔ نکته‌ها با
 *    همان آستانه.
 * ۲) برچسبِ «دانشجو پرسید» فقط از روی شاهد ساخته می‌شود. جفتی که نقل‌قولِ
 *    پرسشش تأیید نشود، یا از دهانِ استاد درآمده باشد، به «سؤال خودآزمایی»
 *    تنزل می‌کند — نه اینکه با ادعای غلط چاپ شود.
 *
 * دستهٔ «باید تنزل کند» مهم‌ترین بخش این آزمون است: حذف را کاربر می‌بیند
 * (چیزی کم است)، ولی برچسبِ غلط را نمی‌بیند و همان است که به او می‌گوید
 * سؤالی سرِ کلاس پرسیده شده که هیچ‌کس نپرسیده.
 */
import { buildTranscript } from "../src/stt/transcript.ts";
import { gateQaPairs } from "../src/analysis/analyze.ts";
import { MAX_QA_PAIRS } from "../src/analysis/schema.ts";

let bad = 0;
const fail = (msg) => {
  console.log(`❌ ${msg}`);
  bad++;
};

const tok = (text, startMs, speaker) => ({
  text,
  start_ms: startMs,
  end_ms: startMs + 4000,
  speaker,
  confidence: 0.99,
});

/**
 * رونوشتِ ساختگی با تفکیکِ گویندهٔ **قطعی**: گویندهٔ ۱ باید بیش از ۶۰٪ گفتار
 * و دو برابرِ نفر دوم باشد وگرنه هیچ‌کس نقش نمی‌گیرد و کلِ این آزمون بی‌معنا
 * می‌شود. متن‌های استاد عمداً بلندند تا آن شرط برقرار شود.
 */
const t = buildTranscript(
  [
    tok("عقد لازم عقدی است که هیچ‌کدام از طرفین حق فسخ آن را ندارند مگر در موارد قانونی مشخص شده. ", 60_000, "1"),
    tok("استاد ببخشید، پس وکالت چه نوع عقدی حساب می‌شود؟", 120_000, "2"),
    tok("وکالت عقد جایز است، یعنی هر کدام از طرفین هر وقت بخواهد می‌تواند آن را بر هم بزند و این تفاوت اصلی‌اش با عقد لازم است. ", 130_000, "1"),
    tok("تفاوت عقد معین و نامعین در این است که عقد معین در قانون نام و احکام مشخص دارد و نامعین ندارد. ", 200_000, "1"),
  ],
  { toOriginal: (ms) => ms, skippedMs: 0 },
);

if (t.utterances.some((u) => u.role === "نامشخص")) {
  fail("پیش‌شرط آزمون برقرار نشد: نقش گوینده‌ها تفکیک نشد");
}

const ev = (quote, atMs, speaker) => ({ quote, at_ms: atMs, speaker });

// ── ۱) پاسخِ ناگفته حذف می‌شود ───────────────────────────────────────────
{
  const r = gateQaPairs(t, [
    {
      answer_evidence: ev("عقد جایز در امتحان بیست نمره دارد و حتماً می‌آید", 130_000, "استاد"),
      question_evidence: null,
      question: "وکالت چه نوع عقدی است؟",
      answer: "عقد جایز.",
    },
  ]);
  if (r.kept.length !== 0) fail("پاسخی که در رونوشت نیست باید جفت را حذف کند");
  if (r.dropped !== 1) fail(`حذف باید در شمارنده بیاید — شد ${r.dropped}`);
}

// ── ۲) پرسشِ واقعیِ دانشجو، با شاهدِ خودش ────────────────────────────────
{
  const r = gateQaPairs(t, [
    {
      answer_evidence: ev("وکالت عقد جایز است، یعنی هر کدام از طرفین هر وقت بخواهد", 130_000, "استاد"),
      question_evidence: ev("استاد ببخشید، پس وکالت چه نوع عقدی حساب می‌شود؟", 120_000, "دانشجو"),
      question: "وکالت چه نوع عقدی است؟",
      answer: "عقد جایز است و هر طرف هر وقت بخواهد می‌تواند آن را بر هم بزند.",
    },
  ]);
  if (r.kept.length !== 1) fail("جفتِ با هر دو شاهدِ تأییدشده باید بماند");
  else if (r.kept[0].source !== "asked") fail(`برچسب باید «asked» می‌بود — شد ${r.kept[0].source}`);
  else if (!r.kept[0].question_evidence) fail("شاهدِ پرسش باید نگه داشته می‌شد");
  if (r.demoted !== 0) fail("جفتِ سالم نباید تنزل بخورد");
}

// ── ۳) شاهدِ پرسشِ ساختگی ⇒ تنزل، نه حذف و نه ادعای غلط ──────────────────
{
  const r = gateQaPairs(t, [
    {
      answer_evidence: ev("وکالت عقد جایز است", 130_000, "استاد"),
      question_evidence: ev("استاد این سؤال توی امتحان هم میاد؟", 120_000, "دانشجو"),
      question: "وکالت چه نوع عقدی است؟",
      answer: "عقد جایز است.",
    },
  ]);
  if (r.kept.length !== 1) fail("شاهدِ پرسشِ تأییدنشده نباید کلِ جفت را بکشد");
  else if (r.kept[0].source !== "implied") fail("جفت باید به «implied» تنزل می‌کرد");
  else if (r.kept[0].question_evidence !== null) fail("شاهدِ تأییدنشده نباید نمایش داده شود");
  if (r.demoted !== 1) fail(`تنزل باید شمرده شود — شد ${r.demoted}`);
}

// ── ۴) جمله‌ای که استاد گفته، «پرسشِ دانشجو» نیست ────────────────────────
{
  const r = gateQaPairs(t, [
    {
      answer_evidence: ev("وکالت عقد جایز است، یعنی هر کدام از طرفین", 130_000, "استاد"),
      question_evidence: ev("تفاوت عقد معین و نامعین در این است که", 200_000, "دانشجو"),
      question: "تفاوت عقد معین و نامعین چیست؟",
      answer: "معین در قانون نام و احکام دارد.",
    },
  ]);
  if (r.kept[0]?.source !== "implied") {
    fail("نقل‌قولی که مالکش استاد است نباید برچسبِ «دانشجو پرسید» بگیرد");
  }
}

// ── ۵) پاسخی که از دهان دانشجو درآمده، پاسخِ درس نیست ───────────────────
{
  const r = gateQaPairs(t, [
    {
      answer_evidence: ev("استاد ببخشید، پس وکالت چه نوع عقدی حساب می‌شود؟", 120_000, "استاد"),
      question_evidence: null,
      question: "وکالت چه نوع عقدی است؟",
      answer: "عقد جایز.",
    },
  ]);
  if (r.kept.length !== 0) fail("پاسخی که گوینده‌اش دانشجوست باید حذف شود");
  if (r.dropped !== 1) fail("حذفِ پاسخِ دانشجو هم باید شمرده شود");
}

// ── ۶) سقف ده و تکراری‌زدایی، در کد نه در پرامپت ────────────────────────
{
  const one = {
    answer_evidence: ev("عقد لازم عقدی است که هیچ‌کدام از طرفین حق فسخ آن را ندارند", 60_000, "استاد"),
    question_evidence: null,
    question: "عقد لازم چیست؟",
    answer: "عقدی که طرفین حق فسخ ندارند.",
  };
  const dup = gateQaPairs(t, [one, { ...one }]);
  if (dup.kept.length !== 1) fail(`دو جفت با یک نقل‌قول باید یکی شوند — شد ${dup.kept.length}`);

  // دوازده جفتِ متمایز از دو پاره‌گفتار مختلف، تا سقف واقعاً آزموده شود
  const many = Array.from({ length: 12 }, (_, i) => ({
    answer_evidence:
      i % 2 === 0
        ? ev("عقد لازم عقدی است که هیچ‌کدام از طرفین حق فسخ آن را ندارند", 60_000, "استاد")
        : ev("تفاوت عقد معین و نامعین در این است که عقد معین در قانون نام", 200_000, "استاد"),
    question_evidence: null,
    question: `سؤال ${i}`,
    answer: "…",
  }));
  const capped = gateQaPairs(t, many);
  if (capped.kept.length > MAX_QA_PAIRS) fail(`سقف ${MAX_QA_PAIRS} اعمال نشد — ${capped.kept.length}`);
}

// ── ۷) جفتِ `asked` بالای فهرست می‌نشیند ────────────────────────────────
{
  const r = gateQaPairs(t, [
    {
      answer_evidence: ev("تفاوت عقد معین و نامعین در این است که عقد معین در قانون نام", 200_000, "استاد"),
      question_evidence: null,
      question: "تفاوت معین و نامعین؟",
      answer: "…",
    },
    {
      answer_evidence: ev("وکالت عقد جایز است، یعنی هر کدام از طرفین هر وقت بخواهد", 130_000, "استاد"),
      question_evidence: ev("استاد ببخشید، پس وکالت چه نوع عقدی حساب می‌شود؟", 120_000, "دانشجو"),
      question: "وکالت چه نوع عقدی است؟",
      answer: "…",
    },
  ]);
  if (r.kept[0]?.source !== "asked") fail("پرسشِ واقعیِ دانشجو باید بالای فهرست بیاید");
}

console.log(bad === 0 ? "✅ همه سبز" : `${bad} مورد اشتباه.`);
process.exit(bad === 0 ? 0 : 1);
